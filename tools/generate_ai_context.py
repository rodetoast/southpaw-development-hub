"""Generate the offline AI reference from committed, public Markdown."""

import json
from datetime import datetime, timedelta, timezone
from pathlib import Path
import re
import subprocess
from urllib.parse import quote, urljoin
from urllib.request import Request, urlopen


ROOT = Path(__file__).resolve().parents[1]
HUB = "https://github.com/rodetoast/southpaw-development-hub"
OUTPUT = "SOUTHPAW_AI_CONTEXT.md"
COMMON_DOCS = (
    "docs/AI_START_HERE.md",
    "docs/DEVELOPMENT_RULES.md",
    "docs/RELEASE_GUIDE.md",
    "docs/PROJECTS.md",
    "docs/DECISIONS.md",
)
STATUS_LINK = re.compile(
    r"\]\((https://github\.com/(rodetoast/[\w.-]+)/blob/"
    r"([\w./-]+)/docs/PROJECT_STATUS\.md)\)"
)
RELATIVE_LINK = re.compile(r"\]\((?![a-z][a-z\d+.-]*:|[/#])([^)\s]+)\)", re.I)
COMMIT_SHA = re.compile(r"[0-9a-f]{40}")


def git(*args):
    return subprocess.check_output(["git", "-C", str(ROOT), *args]).decode("utf-8")


def public_text(url, accept):
    request = Request(url, headers={"Accept": accept, "User-Agent": "Southpaw-AI-Context"})
    with urlopen(request, timeout=30) as response:
        return response.read().decode("utf-8")


def render(markdown, source_url, depth):
    def expand_link(match):
        link = match[1]
        if Path(link).name == OUTPUT:
            return f"]({HUB}/blob/main/{OUTPUT})"
        return f"]({urljoin(source_url, link)})"

    body = RELATIVE_LINK.sub(expand_link, markdown.strip())
    return re.sub(r"(?m)^(#{1,4})(?= )", lambda m: "#" * depth + m[1], body)


def project_detail(summary):
    match = STATUS_LINK.search(summary)
    if not match:
        return None
    url, repository, branch = match.groups()
    api = f"https://api.github.com/repos/{repository}/commits/{quote(branch, safe='')}"
    commit = json.loads(public_text(api, "application/vnd.github+json"))["sha"]
    if not COMMIT_SHA.fullmatch(commit):
        raise ValueError(f"Invalid GitHub commit for {repository}")
    path = "docs/PROJECT_STATUS.md"
    raw = f"https://raw.githubusercontent.com/{repository}/{commit}/{path}"
    body = public_text(raw, "text/plain")
    if not body.lstrip().startswith("# "):
        raise ValueError(f"Expected Markdown at {url}")
    pinned = f"https://github.com/{repository}/blob/{commit}/{path}"
    return (
        f"[상세 상태 최신 링크]({url}) · [이 파일의 원본 {commit[:7]}]({pinned})\n\n"
        + render(body, pinned, depth=3)
    )


def generate():
    commit = git("rev-parse", "HEAD").strip()
    base = f"{HUB}/blob/{commit}/"
    day = datetime.now(timezone(timedelta(hours=9))).date()
    sections = [
        "# Southpaw Games AI Context",
        "<!-- Generated by tools/generate_ai_context.py. Edit the source documents. -->",
        f"- 생성일 {day} (한국 시간)\n"
        f"- [중앙 개발 허브]({HUB})\n"
        f"- [허브 문서 기준 커밋]({HUB}/commit/{commit}) {commit}",
        "웹 접근이 제한된 ChatGPT 프로젝트에 올리는 참조 파일입니다. "
        "공개 원본을 읽을 수 있으면 원본을 우선합니다. "
        "아래 운영 버전·검증 상태는 인용한 문서의 확인일 기준입니다.",
    ]
    for path in COMMON_DOCS:
        sections.append(render(git("show", f"{commit}:{path}"), base + path, depth=1))

    sections.append("## 프로그램별 요약과 상세 상태")
    paths = git("ls-tree", "-r", "--name-only", commit, "--", "projects").splitlines()
    for path in paths:
        if not path.endswith(".md"):
            continue
        summary = git("show", f"{commit}:{path}")
        sections.append(render(summary, base + path, depth=2))
        detail = project_detail(summary)
        if detail:
            sections.append(detail)

    (ROOT / OUTPUT).write_text("\n\n".join(sections) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    generate()
